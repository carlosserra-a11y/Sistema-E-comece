-- Venda presencial (balcão): clientes, serviços, caixa, vendas/orçamentos e configuração do Pix. Dinheiro em centavos; datas em ms UTC.
-- Versão PostgreSQL de migrations/009_vendas.sql (SQLite). Mantenha as duas em sincronia.

CREATE TABLE clientes (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                TEXT NOT NULL,
  busca               TEXT NOT NULL,
  documento_enc       TEXT,
  documento_hmac      TEXT UNIQUE,
  documento_mascarado TEXT,
  telefone            TEXT,
  email               TEXT,
  endereco            TEXT,
  observacoes         TEXT,
  ativo               INTEGER NOT NULL DEFAULT 1,
  versao              INTEGER NOT NULL DEFAULT 1,
  criado_em           BIGINT NOT NULL,
  atualizado_em       BIGINT NOT NULL
);
CREATE INDEX idx_clientes_busca ON clientes(busca);

CREATE TABLE servicos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           TEXT NOT NULL,
  busca          TEXT NOT NULL,
  valor_centavos BIGINT NOT NULL CHECK (valor_centavos >= 0),
  ativo          INTEGER NOT NULL DEFAULT 1,
  versao         INTEGER NOT NULL DEFAULT 1,
  criado_em      BIGINT NOT NULL,
  atualizado_em  BIGINT NOT NULL
);

CREATE TABLE config_vendas (
  id                      INTEGER PRIMARY KEY CHECK (id = 1),
  pix_chave               TEXT,
  pix_nome                TEXT,
  pix_cidade              TEXT,
  desconto_max_pct        INTEGER NOT NULL DEFAULT 0 CHECK (desconto_max_pct BETWEEN 0 AND 100),
  validade_orcamento_dias INTEGER NOT NULL DEFAULT 7 CHECK (validade_orcamento_dias BETWEEN 1 AND 90),
  cupom_rodape            TEXT,
  atualizado_em           BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE caixas (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aberto_por        INTEGER NOT NULL REFERENCES users(id),
  aberto_em         BIGINT NOT NULL,
  abertura_centavos BIGINT NOT NULL CHECK (abertura_centavos >= 0),
  status            TEXT NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO','FECHADO')),
  fechado_por       INTEGER REFERENCES users(id),
  fechado_em        BIGINT,
  contado_centavos  BIGINT CHECK (contado_centavos IS NULL OR contado_centavos >= 0),
  esperado_centavos BIGINT,
  resumo            TEXT,
  observacao        TEXT
);
CREATE UNIQUE INDEX uq_caixa_aberto ON caixas(aberto_por) WHERE status = 'ABERTO';

CREATE TABLE vendas (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status              TEXT NOT NULL CHECK (status IN ('ORCAMENTO','CONCLUIDA','CANCELADA','DESCARTADA')),
  cliente_id          INTEGER REFERENCES clientes(id),
  vendedor_id         INTEGER NOT NULL REFERENCES users(id),
  caixa_id            INTEGER REFERENCES caixas(id),
  subtotal_centavos   BIGINT NOT NULL CHECK (subtotal_centavos >= 0),
  desconto_centavos   BIGINT NOT NULL DEFAULT 0 CHECK (desconto_centavos >= 0),
  valor_centavos      BIGINT NOT NULL CHECK (valor_centavos > 0),
  troco_centavos      BIGINT NOT NULL DEFAULT 0 CHECK (troco_centavos >= 0),
  observacao          TEXT,
  validade            TEXT,
  criado_em           BIGINT NOT NULL,
  concluida_em        BIGINT,
  cancelada_em        BIGINT,
  cancelada_por       INTEGER REFERENCES users(id),
  motivo_cancelamento TEXT,
  CHECK (valor_centavos = subtotal_centavos - desconto_centavos),
  CHECK (status NOT IN ('CONCLUIDA','CANCELADA') OR (caixa_id IS NOT NULL AND concluida_em IS NOT NULL))
);
CREATE INDEX idx_vendas_status ON vendas(status, concluida_em);
CREATE INDEX idx_vendas_caixa ON vendas(caixa_id);
CREATE INDEX idx_vendas_cliente ON vendas(cliente_id);
CREATE INDEX idx_vendas_vendedor ON vendas(vendedor_id);
CREATE INDEX idx_vendas_cancelada_por ON vendas(cancelada_por);

CREATE TABLE venda_itens (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id              INTEGER NOT NULL REFERENCES vendas(id),
  tipo                  TEXT NOT NULL CHECK (tipo IN ('PRODUTO','SERVICO')),
  produto_id            INTEGER REFERENCES produtos(id),
  servico_id            INTEGER REFERENCES servicos(id),
  codigo                TEXT,
  descricao             TEXT NOT NULL,
  unidade               TEXT NOT NULL DEFAULT 'UN',
  qtd                   INTEGER NOT NULL CHECK (qtd > 0),
  preco_tabela_centavos BIGINT NOT NULL CHECK (preco_tabela_centavos >= 0),
  preco_unit_centavos   BIGINT NOT NULL CHECK (preco_unit_centavos >= 0),
  custo_unit_centavos   BIGINT NOT NULL DEFAULT 0 CHECK (custo_unit_centavos >= 0),
  CHECK ((tipo = 'PRODUTO' AND produto_id IS NOT NULL AND servico_id IS NULL) OR (tipo = 'SERVICO' AND servico_id IS NOT NULL AND produto_id IS NULL))
);
CREATE INDEX idx_venda_itens_venda ON venda_itens(venda_id);
CREATE INDEX idx_venda_itens_produto ON venda_itens(produto_id);
CREATE INDEX idx_venda_itens_servico ON venda_itens(servico_id);

CREATE TABLE venda_pagamentos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id       INTEGER NOT NULL REFERENCES vendas(id),
  forma          TEXT NOT NULL CHECK (forma IN ('DINHEIRO','PIX','DEBITO','CREDITO')),
  valor_centavos BIGINT NOT NULL CHECK (valor_centavos > 0),
  parcelas       INTEGER NOT NULL DEFAULT 1 CHECK (parcelas BETWEEN 1 AND 24)
);
CREATE INDEX idx_venda_pag_venda ON venda_pagamentos(venda_id);

CREATE TABLE caixa_movimentos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caixa_id       INTEGER NOT NULL REFERENCES caixas(id),
  ts             BIGINT NOT NULL,
  tipo           TEXT NOT NULL CHECK (tipo IN ('SUPRIMENTO','SANGRIA','ESTORNO')),
  valor_centavos BIGINT NOT NULL CHECK (valor_centavos > 0),
  motivo         TEXT NOT NULL,
  venda_id       INTEGER REFERENCES vendas(id),
  user_id        INTEGER NOT NULL REFERENCES users(id)
);
CREATE INDEX idx_caixa_mov ON caixa_movimentos(caixa_id);

-- Dinheiro registrado não se reescreve nem se apaga (fn_somente_insercao já existe desde o esquema inicial).
CREATE TRIGGER trg_venda_pag_no_update BEFORE UPDATE ON venda_pagamentos FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_venda_pag_no_delete BEFORE DELETE ON venda_pagamentos FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_caixa_mov_no_update BEFORE UPDATE ON caixa_movimentos FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_caixa_mov_no_delete BEFORE DELETE ON caixa_movimentos FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_vendas_no_delete BEFORE DELETE ON vendas FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_venda_itens_no_delete BEFORE DELETE ON venda_itens FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_caixas_no_delete BEFORE DELETE ON caixas FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();

CREATE INDEX idx_mov_grupo ON movimentacoes_estoque(grupo);
