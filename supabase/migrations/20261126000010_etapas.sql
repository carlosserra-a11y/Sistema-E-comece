-- Rastreio da venda (quem separou, conferiu e expediu; só se insere) e exclusão de contas da equipe.
-- Versão PostgreSQL de migrations/010_etapas.sql.
CREATE TABLE etapas (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id   INTEGER NOT NULL REFERENCES vendas(id),
  etapa      TEXT NOT NULL CHECK (etapa IN ('SEPARACAO','CONFERENCIA','EXPEDICAO')),
  user_id    INTEGER NOT NULL REFERENCES users(id),
  ts         BIGINT NOT NULL,
  observacao TEXT,
  UNIQUE (venda_id, etapa)
);
CREATE INDEX idx_etapas_ts ON etapas(ts);
CREATE INDEX idx_etapas_user ON etapas(user_id);
CREATE TRIGGER trg_etapas_no_update BEFORE UPDATE ON etapas FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();
CREATE TRIGGER trg_etapas_no_delete BEFORE DELETE ON etapas FOR EACH ROW EXECUTE FUNCTION fn_somente_insercao();

ALTER TABLE users ADD COLUMN excluido_em BIGINT;
