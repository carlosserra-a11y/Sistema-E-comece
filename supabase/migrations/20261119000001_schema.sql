-- Esquema PostgreSQL (Supabase) do sistema. É a versão em Postgres das migrations/001..005 do SQLite (usado só em desenvolvimento/testes).
-- Regras de portabilidade: ids INTEGER identity; carimbos de tempo em milissegundos = BIGINT; flags 0/1 = INTEGER (o código usa 1/0);
-- triggers em PL/pgSQL. Mantenha as duas versões em sincronia (o conjunto de testes roda nos dois motores).

CREATE TABLE users (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_hmac         TEXT NOT NULL UNIQUE,
  senha_hash         TEXT NOT NULL,
  papel              TEXT NOT NULL DEFAULT 'admin',
  nome               TEXT NOT NULL DEFAULT 'Administrador',
  trocar_senha       INTEGER NOT NULL DEFAULT 1,
  mfa_ativo          INTEGER NOT NULL DEFAULT 0,
  mfa_segredo_enc    TEXT,
  mfa_pendente_enc   TEXT,
  mfa_ultimo_passo   BIGINT NOT NULL DEFAULT 0,
  mfa_falhas         INTEGER NOT NULL DEFAULT 0,
  ativo              INTEGER NOT NULL DEFAULT 1,
  criado_em          BIGINT NOT NULL,
  senha_alterada_em  BIGINT,
  dono               INTEGER NOT NULL DEFAULT 0,
  permissoes         TEXT NOT NULL DEFAULT '[]',
  login_enc          TEXT,
  criado_por         INTEGER REFERENCES users(id)
);
CREATE UNIQUE INDEX idx_users_dono ON users(dono) WHERE dono = 1;

