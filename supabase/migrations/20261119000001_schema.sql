CREATE TABLE saldos_por_endereco (
  produto_id    INTEGER NOT NULL REFERENCES produtos(id),
  endereco_id   INTEGER NOT NULL REFERENCES enderecos(id),
  lote_id       INTEGER NOT NULL DEFAULT 0,
  qtd           INTEGER NOT NULL,
  atualizado_em BIGINT NOT NULL,
  PRIMARY KEY (produto_id, endereco_id, lote_id),
  CONSTRAINT saldos_por_endereco_qtd_check CHECK (qtd >= 0)
);
CREATE INDEX idx_saldos_endereco ON saldos_por_endereco(endereco_id);

-- Único caminho de escrita nos saldos. UPDATE antes do INSERT: o CHECK (qtd >= 0) é avaliado na linha proposta de um UPSERT,
-- o que rejeitaria toda saída. A trava por chave evita duas "primeiras entradas" simultâneas na mesma posição.
CREATE FUNCTION fn_mov_saldo() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('saldo|' || NEW.produto_id || '|' || NEW.endereco_id || '|' || NEW.lote_id));
  UPDATE saldos_por_endereco SET qtd = qtd + NEW.delta, atualizado_em = NEW.ts
   WHERE produto_id = NEW.produto_id AND endereco_id = NEW.endereco_id AND lote_id = NEW.lote_id;
  IF NOT FOUND THEN
    INSERT INTO saldos_por_endereco (produto_id, endereco_id, lote_id, qtd, atualizado_em)
    VALUES (NEW.produto_id, NEW.endereco_id, NEW.lote_id, NEW.delta, NEW.ts);
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_mov_saldo AFTER INSERT ON movimentacoes_estoque FOR EACH ROW EXECUTE FUNCTION fn_mov_saldo();

